#!/usr/bin/env node

/**
 * REA // CTF REV SOLVER CLI
 * High-speed CTF Reverse Engineering wrapper powered by Ghidra and REA
 */

import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { existsSync, writeFileSync } from "node:fs";
import { spawn } from "node:child_process";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

// Auto-discover Ghidra
if (!process.env.GHIDRA_INSTALL_DIR) {
  const candidateDirs = [
    process.env.GHIDRA_INSTALL_DIR,
    resolve(packageRoot, "..", "ghidra"),
    resolve(packageRoot, "ghidra"),
    resolve(process.cwd(), "..", "ghidra"),
    resolve(process.cwd(), "ghidra"),
    "/usr/share/ghidra",
    "/usr/lib/ghidra",
    "/opt/ghidra",
    "/usr/local/ghidra",
    "C:\\tools\\ghidra",
  ].filter(Boolean);
  for (const dir of candidateDirs) {
    if (existsSync(dir) && existsSync(join(dir, "Ghidra", "application.properties"))) {
      process.env.GHIDRA_INSTALL_DIR = dir;
      break;
    }
  }
}

// Auto-discover IDA MCP config
if (!process.env.REA_IDA_MCP_CONFIG) {
  const idaCandidate = resolve(packageRoot, "config", "ida-mcp.json");
  if (existsSync(idaCandidate)) {
    process.env.REA_IDA_MCP_CONFIG = idaCandidate;
  }
}

if (!process.env.REA_ANALYSIS_PROVIDER) {
  process.env.REA_ANALYSIS_PROVIDER = "ghidra";
}

const args = process.argv.slice(2);
const command = args[0];

function printHelp() {
  console.log(`
============================================================
  REA // CTF REVERSE ENGINEERING SOLVER (CLI MODE)
============================================================

Usage:
  node scripts/ctf.mjs <command> [arguments]
  npm run ctf -- <command> [arguments]

Commands:
  inspect   <binary>              Run full Ghidra binary overview & layout
  decompile <binary> <address>    Decompile function at hex address or symbol
  disasm    <binary> <address>    Dump raw instructions at address
  strings   <binary> [filter]     Search strings in the binary
  xrefs     <binary> <address>    Find cross-references to address
  template  <binary> [out.py]     Generate CTF Python solver script (pwntools + z3)
  doctor                          Verify Ghidra & CTF environment health

Examples:
  npm run ctf -- inspect ./challenge.elf
  npm run ctf -- decompile ./challenge.elf main
  npm run ctf -- disasm ./challenge.elf 0x401120
  npm run ctf -- strings ./challenge.elf "flag{"
  npm run ctf -- template ./challenge.elf solve.py
`);
}

function resolveTarget(pathArg) {
  if (!pathArg) return null;
  const callerCwd = process.env.INIT_CWD || process.cwd();
  const absPath = resolve(callerCwd, pathArg);
  if (!existsSync(absPath)) {
    console.error(`[-] Target binary not found: ${absPath}`);
    console.error(`    Checked relative to caller directory: ${callerCwd}`);
    process.exit(1);
  }
  return absPath;
}

function runReaCommand(cmdArgs) {
  const reaScript = join(packageRoot, "scripts", "rea.mjs");
  const child = spawn(process.execPath, [reaScript, ...cmdArgs], {
    stdio: "inherit",
    env: process.env,
  });
  child.on("exit", (code) => {
    process.exit(code ?? 0);
  });
}

function generateSolveTemplate(binaryPath, outputPath = "solve.py") {
  const callerCwd = process.env.INIT_CWD || process.cwd();
  const targetAbs = resolve(callerCwd, binaryPath);
  const targetBase = targetAbs.split(/[\\/]/).pop();
  const outAbs = resolve(callerCwd, outputPath);

  const script = `#!/usr/bin/env python3
"""
CTF Reverse Engineering Solver Script
Target: ${targetBase}
Generated by REA CTF Solver
"""

import sys
from pwn import *
from z3 import *

context.binary = '${targetBase}'
# context.log_level = 'debug'

def solve():
    print("[*] Setting up Z3 constraint solver...")
    s = Solver()

    # Define flag variables (e.g. 32-byte flag)
    FLAG_LEN = 32
    flag = [BitVec(f'flag_{i}', 8) for i in range(FLAG_LEN)]

    # Printable ASCII constraints
    for i in range(FLAG_LEN):
        s.add(flag[i] >= 0x20, flag[i] <= 0x7E)

    # Known flag prefix (e.g. CTF{ or BUP{)
    prefix = b"CTF{"
    for i, b in enumerate(prefix):
        s.add(flag[i] == b)
    s.add(flag[-1] == ord('}'))

    # --- ADD DECOMPILED VERIFICATION CONSTRAINTS HERE ---
    # Example:
    # s.add(flag[4] ^ 0x42 == 0x13)
    # s.add((flag[5] * 0x45f3) & 0xFF == 0xAA)

    print("[*] Checking satisfiability...")
    if s.check() == sat:
        m = s.model()
        recovered = bytes([m[b].as_long() for b in flag])
        print(f"[+] Flag found: {recovered.decode('latin1', errors='replace')}")
        return recovered
    else:
        print("[-] Unsatisfiable constraints! Check logic.")
        return None

def exploit_remote(host, port):
    r = remote(host, port)
    flag = solve()
    if flag:
        r.sendline(flag)
        r.interactive()

if __name__ == "__main__":
    if len(sys.argv) > 2:
        exploit_remote(sys.argv[1], int(sys.argv[2]))
    else:
        solve()
`;

  writeFileSync(outAbs, script, "utf8");
  console.log(`[+] Generated CTF solver script: ${outAbs}`);
  console.log(`[+] Run with: python ${outAbs}`);
}

switch (command) {
  case "inspect": {
    const target = resolveTarget(args[1]);
    if (!target) {
      console.error("Error: Please provide a target binary path.");
      process.exit(1);
    }
    runReaCommand(["inspect", target]);
    break;
  }
  case "decompile": {
    const target = resolveTarget(args[1]);
    const addr = args[2];
    if (!target || !addr) {
      console.error("Usage: npm run ctf -- decompile <binary> <address_or_symbol>");
      process.exit(1);
    }
    runReaCommand(["decompile", target, addr, "--filter-output", "normalized_result"]);
    break;
  }
  case "disasm": {
    const target = resolveTarget(args[1]);
    const addr = args[2];
    if (!target || !addr) {
      console.error("Usage: npm run ctf -- disasm <binary> <address_or_symbol>");
      process.exit(1);
    }
    runReaCommand(["instructions", target, addr, "--filter-output", "normalized_result"]);
    break;
  }
  case "strings": {
    const target = resolveTarget(args[1]);
    const query = args[2] || "";
    if (!target) {
      console.error("Usage: npm run ctf -- strings <binary> [filter]");
      process.exit(1);
    }
    const cmd = ["search", target];
    if (query) cmd.push(query);
    cmd.push("--filter-output", "normalized_result");
    runReaCommand(cmd);
    break;
  }
  case "xrefs": {
    const target = resolveTarget(args[1]);
    const addr = args[2];
    if (!target || !addr) {
      console.error("Usage: npm run ctf -- xrefs <binary> <address_or_symbol>");
      process.exit(1);
    }
    runReaCommand(["xrefs", target, addr, "--filter-output", "normalized_result"]);
    break;
  }
  case "template": {
    const target = args[1] || "target.exe";
    const out = args[2] || "solve.py";
    generateSolveTemplate(target, out);
    break;
  }
  case "doctor": {
    runReaCommand(["doctor", "--provider", "ghidra"]);
    break;
  }
  default: {
    printHelp();
    break;
  }
}
